create table public.sessions (
  id bigint generated by default as identity not null,
  title text not null,
  program text not null,
  year text not null,
  section text not null,
  date date not null,
  time_in text null,
  time_out text null,
  type text not null default 'class'::text,
  created_at timestamp with time zone null default now(),
  updated_at timestamp with time zone null default now(),
  created_by_user_id uuid null,
  status text not null default 'not completed'::text,
  constraint sessions_pkey primary key (id),
  constraint sessions_created_by_user_id_check check (
    (
      (created_by_user_id is null)
      or check_account_exists (created_by_user_id)
    )
  ),
  constraint sessions_status_check check (
    (
      status = any (array['not completed'::text, 'completed'::text])
    )
  ),
  constraint sessions_type_check check (
    (
      type = any (
        array['class'::text, 'event'::text, 'other'::text]
      )
    )
  )
) TABLESPACE pg_default;

create index IF not exists idx_sessions_program_year_section on public.sessions using btree (program, year, section) TABLESPACE pg_default;

create trigger update_sessions_updated_at BEFORE
update on sessions for EACH row
execute FUNCTION update_updated_at_column ();



