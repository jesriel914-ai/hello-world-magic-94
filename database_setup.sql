create table public.attendance (
  id bigint generated by default as identity not null,
  session_id bigint not null,
  student_id bigint not null,
  status text not null,
  time_in timestamp with time zone null,
  time_out timestamp with time zone null,
  created_at timestamp with time zone null default now(),
  updated_at timestamp with time zone null default now(),
  constraint attendance_pkey primary key (id),
  constraint attendance_session_id_student_id_key unique (session_id, student_id),
  constraint attendance_session_id_fkey foreign KEY (session_id) references sessions (id) on delete CASCADE,
  constraint attendance_student_id_fkey foreign KEY (student_id) references students (id) on delete CASCADE,
  constraint attendance_status_check check (
    (
      status = any (
        array[
          'present'::text,
          'absent'::text,
          'late'::text,
          'excused'::text
        ]
      )
    )
  )
) TABLESPACE pg_default;

create index IF not exists idx_attendance_session_id on public.attendance using btree (session_id) TABLESPACE pg_default;

create index IF not exists idx_attendance_student_id on public.attendance using btree (student_id) TABLESPACE pg_default;

create trigger update_attendance_updated_at BEFORE
update on attendance for EACH row
execute FUNCTION update_updated_at_column ();




